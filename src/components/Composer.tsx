import { useEffect, useRef, useState } from "react";
import type { DuoApiConfig } from "../api/client.js";
import { useCreateDraftStream } from "../api/queries.js";
import { readComposerBuffer, writeComposerBuffer } from "../composerBuffer.js";
import { MutationError } from "./MutationError.js";
import { useSyncStatus } from "../sync.js";
import { Mark } from "./Mark.js";
import { ChatEditor, type ChatEditorHandle } from "../composer/ChatEditor.js";

/**
 * The thread view's ask input — the owner's way into the drafting loop
 * without a terminal (`client-tech-design.md` §3.1's "thread view +
 * composer"). Disposition (Send / Edit / Ignore / answer-an-escalation)
 * stays in Review: asking is a conversation act, disposing is a triage
 * act, and the draft the daemon returns is pending either way.
 *
 * The field is the app's one composer editor (#248: `ChatEditor`, in plain
 * mode — a question carries no formatting). A real question is rarely one
 * line, so Shift+Enter is a new line, and Enter (or Cmd/Ctrl-Enter) asks —
 * the convention every messenger uses (#244). The typed question survives
 * a failed submit (the editor clears in `onSuccess` only), a cancelled one (abort is
 * the owner's choice, not a failure — so it resets, not errors), and a
 * route switch (kept in `composerBuffer` outside the component, because
 * a half-typed question is a thought in progress, not a record). AR-15
 * applies as it does in DraftCard: unreachable disables submission
 * rather than queueing it.
 *
 * duo#304: asks stream through `POST /drafts/stream` (`useCreateDraftStream`)
 * instead of the blocking `POST /drafts`. `onAsk`/`onChunk` let `Duo.tsx`
 * (this component's one caller) render the answer as it arrives, in the
 * transcript rather than only in this composer's own "Asking…" state.
 * Cancel still aborts the one in-flight request exactly as before; the
 * daemon has already written the full draft row by the time any text
 * streams (`client-tech-design.md` §1.4's `/drafts/stream` row), so an
 * abort here only ends the reveal, never the answer itself.
 */
export function Composer({
  api,
  thread,
  threadLabel,
  onAsk,
  onChunk,
  onAskFailed,
}: {
  api: DuoApiConfig;
  thread: string | null;
  threadLabel?: string;
  /** duo#304: fired once, synchronously, right before the request starts — the question text, so the caller can show a live bubble immediately. */
  onAsk?: (question: string) => void;
  /** duo#304: fired for each revealed piece of text, in order; concatenating every call reproduces the final answer. */
  onChunk?: (text: string) => void;
  /**
   * duo#304: fired on a genuine failure — never on the owner's own Stop
   * (that's `cancelledByOwner` below, a reset, not a failure) — so the
   * caller can drop a live bubble that nothing is ever going to finish.
   * `MutationError` still shows the error itself; this only clears the
   * transient "writing…" state riding alongside it.
   */
  onAskFailed?: () => void;
}) {
  const { mutation: createDraft, cancel } = useCreateDraftStream(api);
  const { reachable } = useSyncStatus();
  // Read once: the editor holds the words from here on and reports each change back.
  const [initialQuestion] = useState(readComposerBuffer);
  const [question, setQuestion] = useState(initialQuestion);
  const form = useRef<HTMLFormElement>(null);
  const editor = useRef<ChatEditorHandle>(null);
  const trimmed = question.trim();
  const disabled = trimmed.length === 0 || createDraft.isPending || !reachable;
  // An aborted fetch rejects with a DOMException named "AbortError" — the
  // owner chose to stop, so that's a reset, not a MutationError. The reset
  // lives in an effect rather than right after `cancel()`: the rejection
  // lands a tick later, and resetting synchronously would be undone by it.
  const cancelledByOwner = createDraft.error instanceof DOMException && createDraft.error.name === "AbortError";
  useEffect(() => {
    if (cancelledByOwner) {
      createDraft.reset();
    }
  }, [cancelledByOwner, createDraft]);

  return (
    <form
      className="border-t border-[var(--edge)] p-4"
      data-testid="composer"
      ref={form}
      onSubmit={(e) => {
        e.preventDefault();
        if (disabled) {
          return;
        }
        // No `recipient` (issue #262): this composer is the owner's own
        // private chat with their duo (`Duo.tsx` is its one caller, always
        // with `thread={null}`) — a question asked for themselves, with
        // nobody for the draft to be addressed to. A reply to someone
        // else's question arrives already drafted, generated by the daemon
        // itself the moment the question does (`RoomDrafts.tsx`), with that
        // person as the recipient from the start — never through this call.
        //
        // duo#304: `onAsk` fires synchronously, before the request starts,
        // so `Duo.tsx` can show the live bubble immediately; `onChunk`
        // rides along in the mutation's own variables (`useCreateDraftStream`
        // forwards it straight to `streamDraft`) rather than as a separate
        // argument, so it is in scope for exactly the one request it was
        // given for and never stale across an overlapping ask (disabled
        // while pending anyway, but kept honest either way).
        onAsk?.(trimmed);
        createDraft.mutate(
          { question: trimmed, threadContext: thread, onChunk },
          {
            onSuccess: () => {
              writeComposerBuffer("");
              editor.current?.clear();
            },
            onError: (error) => {
              const aborted = error instanceof DOMException && error.name === "AbortError";
              if (!aborted) {
                onAskFailed?.();
              }
            },
          },
        );
      }}
    >
      <div className="flex items-start gap-2">
        <ChatEditor
          ariaLabel="Question for your duo"
          editorRef={editor}
          initialText={initialQuestion}
          mode="plain"
          placeholder="Ask your duo…"
          onSubmit={() => form.current?.requestSubmit()}
          onTextChange={(text) => {
            setQuestion(text);
            writeComposerBuffer(text);
          }}
        />
        <div className="flex flex-col gap-2">
          <button
            className="inline-flex min-h-11 items-center justify-center gap-2 rounded-[var(--r-sm)] bg-[var(--accent)] px-3 text-[var(--bg)] disabled:opacity-40"
            data-testid="composer-submit"
            disabled={disabled}
            type="submit"
          >
            {createDraft.isPending ? (
              <>
                <Mark working />
                Asking…
              </>
            ) : (
              "Ask"
            )}
          </button>
          {createDraft.isPending && (
            <button
              className="inline-flex min-h-11 items-center justify-center rounded-[var(--r-sm)] border border-[var(--edge)] px-3 text-[var(--muted)]"
              data-testid="composer-cancel"
              onClick={cancel}
              type="button"
            >
              Cancel
            </button>
          )}
        </div>
      </div>
      {threadLabel !== undefined && (
        <p className="mt-2 type-provenance text-[var(--faint)]" data-testid="composer-thread">
          Asking in: {threadLabel}
        </p>
      )}
      <MutationError error={cancelledByOwner ? null : createDraft.error} />
    </form>
  );
}
